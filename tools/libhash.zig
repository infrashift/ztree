//! Write `libhash.go` of the Go binding: the SHA-256 of `libztree.a`
//! (ISSUE-018, ADR-0016). The Go build cache hashes Go source files, but not
//! a library that cgo names with `-l`. A new library changes this Go file,
//! so the next Go build links the new library.
//!
//! Usage: libhash <libztree.a> <libhash.go>

const std = @import("std");

const Sha256 = std.crypto.hash.sha2.Sha256;

/// The largest library that the tool reads.
const max_lib_bytes: usize = 256 * 1024 * 1024;

/// The Go file. `LibraryHash` puts the hash in the compiled package, so the
/// content of the package changes with the library. The Go linker keys on
/// that content, not on the source.
const template =
    \\// Code generated by zig build lib (tools/libhash.zig). DO NOT EDIT.
    \\
    \\package ztree
    \\
    \\// libHash is the SHA-256 of the libztree.a that zig build lib wrote.
    \\const libHash = "{s}"
    \\
    \\// LibraryHash returns the SHA-256 of libztree.a at the time of the build.
    \\// A new library changes it, so the Go build cache links the new library.
    \\func LibraryHash() string {{
    \\
++ "\treturn libHash\n}}\n";

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 3) {
        std.debug.print("usage: libhash <libztree.a> <libhash.go>\n", .{});
        return error.Usage;
    }
    const cwd = std.Io.Dir.cwd();
    const lib = try cwd.readFileAlloc(init.io, args[1], arena, .limited(max_lib_bytes));
    std.debug.assert(lib.len > 0);
    var digest: [Sha256.digest_length]u8 = undefined;
    Sha256.hash(lib, &digest, .{});
    const hex = std.fmt.bytesToHex(digest, .lower);
    const text = try std.fmt.allocPrint(arena, template, .{&hex});
    std.debug.assert(std.mem.indexOf(u8, text, &hex) != null);
    try cwd.writeFile(init.io, .{ .sub_path = args[2], .data = text });
}
